// The .dag file: one or two nodes per job, and the edge between them.
//
// This is the first pipeline in this template whose DAG has real
// edges. BLAST's workflow is a DAG only to get its database into the
// spool once; every node there is independent and writing PARENT/CHILD
// lines would have said something untrue. Here the structure stage
// genuinely cannot start until its own alignment stage has finished,
// and the file it waits for is produced into the workflow's directory
// by the parent. One edge per job, and no edges between jobs: two
// proteins have nothing to do with each other.
//
// With no model weights there is no second stage, so the DAG is the
// alignments alone -- which is a real way to use AlphaFold3 (the
// alignments are the expensive half and they are reusable), not a
// degraded mode.

import {
  EXIT_NO_AF3,
  buildDataSubmit,
  buildInferenceSubmit,
  type NodeSpec,
  type RunSpec,
} from './af3';

/** One job of the run, and the nodes it becomes. */
export interface JobNodes {
  tag: string;
  tokens: number;
  dataNode: string;
  dataSubmit: string;
  inferenceNode?: string;
  inferenceSubmit?: string;
}

export function dataNodeName(index: number): string {
  return `align${index}`;
}
export function inferenceNodeName(index: number): string {
  return `fold${index}`;
}

/**
 * Node names and submit-file names for each job.
 *
 * Names are built from the job's INDEX, not from its tag. A tag is a
 * user's job name with a prefix, and while this app will not accept
 * one that is unsafe as a file name, a DAG node name is a different
 * grammar again -- it is the index that is certain to be a word.
 */
export function planNodes(
  spec: RunSpec,
  jobs: { index: number; tag: string; tokens: number }[],
): JobNodes[] {
  const withInference = spec.weights !== '';
  return jobs.map((j) => {
    const node: NodeSpec = { tag: j.tag, tokens: j.tokens };
    const out: JobNodes = {
      tag: j.tag,
      tokens: j.tokens,
      dataNode: dataNodeName(j.index),
      dataSubmit: buildDataSubmit(spec, node),
    };
    if (withInference) {
      out.inferenceNode = inferenceNodeName(j.index);
      out.inferenceSubmit = buildInferenceSubmit(spec, node);
    }
    return out;
  });
}

export function dataSubmitName(index: number): string {
  return `align${index}.sub`;
}
export function inferenceSubmitName(index: number): string {
  return `fold${index}.sub`;
}

/** The node submit files, by the names they have in the spool. */
export function buildNodeFiles(
  jobs: { index: number }[],
  nodes: JobNodes[],
): Record<string, string> {
  const files: Record<string, string> = {};
  nodes.forEach((n, i) => {
    const index = jobs[i].index;
    files[dataSubmitName(index)] = n.dataSubmit;
    if (n.inferenceSubmit) files[inferenceSubmitName(index)] = n.inferenceSubmit;
  });
  return files;
}

/**
 * The .dag file.
 *
 * RETRY twice, because the failure a long job really sees is an
 * eviction and that deserves another go. UNLESS-EXIT excuses the one
 * that cannot be fixed by asking again: a machine with no AlphaFold3
 * on it. It takes a single code, which is why the runners spend one
 * on exactly that case.
 */
export function buildDagFile(jobs: { index: number }[], nodes: JobNodes[]): string {
  const lines = [
    `# AlphaFold3. Generated by a site app; do not edit here.`,
    `#`,
    `# Two stages per job: alignments on a CPU, then the structure on a`,
    `# GPU. The alignment node writes <job>.data_pipeline.tar.gz into`,
    `# this directory and the structure node reads it from here, which`,
    `# is what the edge below is for.`,
    ``,
  ];
  nodes.forEach((n, i) => {
    const index = jobs[i].index;
    lines.push(`JOB ${n.dataNode} ${dataSubmitName(index)}`);
    if (n.inferenceNode) lines.push(`JOB ${n.inferenceNode} ${inferenceSubmitName(index)}`);
  });
  lines.push(``);
  for (const n of nodes) {
    if (n.inferenceNode) lines.push(`PARENT ${n.dataNode} CHILD ${n.inferenceNode}`);
  }
  lines.push(``);
  for (const n of nodes) {
    lines.push(`RETRY ${n.dataNode} 2 UNLESS-EXIT ${EXIT_NO_AF3}`);
    if (n.inferenceNode) lines.push(`RETRY ${n.inferenceNode} 2 UNLESS-EXIT ${EXIT_NO_AF3}`);
  }
  lines.push(``);
  lines.push(`# Exit ${EXIT_NO_AF3} means the machine had no AlphaFold3 on it, which is`);
  lines.push(`# the same answer however many times it is asked.`);
  lines.push(``);
  return lines.join('\n');
}
